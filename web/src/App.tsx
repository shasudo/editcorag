import { useCallback, useEffect, useState } from "react";
import type { Citation } from "./api";
import { api } from "./api";
import { Chat } from "./components/Chat";
import { DocumentList } from "./components/DocumentList";
import { PdfViewer } from "./components/PdfViewer";

export function App() {
  const [selectedDocs, setSelectedDocs] = useState<number[]>([]);
  const [citation, setCitation] = useState<Citation | null>(null);
  const [info, setInfo] = useState<Record<string, unknown> | null>(null);

  const refreshInfo = useCallback(() => {
    api
      .health()
      .then(setInfo)
      .catch(() => setInfo(null));
  }, []);

  useEffect(refreshInfo, [refreshInfo]);

  const toggleDoc = (id: number) =>
    setSelectedDocs((prev) =>
      prev.includes(id) ? prev.filter((d) => d !== id) : [...prev, id],
    );

  // Answering always runs on Groq, so the header states the split plainly
  // rather than guessing at it from the model id.
  const model = typeof info?.llm_model === "string" ? info.llm_model : "";

  return (
    <div className="flex h-full flex-col bg-[var(--bg)] text-[var(--text)]">
      <header className="flex h-12 shrink-0 items-center gap-3 border-b border-[var(--line)] bg-[var(--surface)] px-4">
        <div className="flex items-center gap-2">
          <img
            src="/logo.png"
            alt=""
            className="h-5 w-5 shrink-0 rounded-[5px]"
          />
          <span className="text-[13px] font-semibold tracking-tight">EditcoRAG</span>
          <span className="hidden text-[11px] text-[var(--text-3)] sm:inline">
            documents &amp; search stay on this machine · answers by Groq
          </span>
        </div>

        {info && (
          <div className="ml-auto flex items-center gap-1.5 text-[11px] text-[var(--text-3)]">
            <span
              className="chip !py-0.5"
              title="Answers are generated by Groq; your documents are not uploaded"
            >
              <span
                className="inline-block h-1.5 w-1.5 rounded-full bg-[var(--accent)]"
              />
              {model}
            </span>
            <span className="chip !py-0.5 tabnum">{String(info.chunks)} chunks</span>
            <span
              className="chip !py-0.5"
              title={
                info.graders_enabled
                  ? "Grades retrieval, retries weak queries, and verifies the answer against the source"
                  : "Retrieve, rerank, then answer"
              }
            >
              {String(info.answer_mode)}
            </span>
          </div>
        )}
      </header>

      <div className="flex min-h-0 flex-1">
        <aside className="w-64 shrink-0 border-r border-[var(--line)] bg-[var(--surface)]">
          <DocumentList
            selected={selectedDocs}
            onToggle={toggleDoc}
            onDocumentsChanged={refreshInfo}
          />
        </aside>

        <main className="min-w-0 flex-1">
          <Chat
            docIds={selectedDocs}
            onSelectCitation={setCitation}
            selectedCitation={citation}
          />
        </main>

        <section className="hidden w-[44%] max-w-[860px] shrink-0 border-l border-[var(--line)] bg-[var(--surface)] xl:block">
          <PdfViewer citation={citation} />
        </section>
      </div>
    </div>
  );
}
